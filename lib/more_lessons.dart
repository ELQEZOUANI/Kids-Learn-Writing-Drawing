// A compact authoring format keeps the expanded library separate from the UI.
// "o" strokes are ellipses; all other strokes are ordered guide points.
List<Offset> _moreStroke(String source) {
  if (source.startsWith('o')) {
    final numbers = source.substring(1).split(',').map(double.parse).toList();
    return _ellipse(numbers[0], numbers[1], numbers[2], numbers[3]);
  }
  return _line(source);
}

LessonData _moreAnimal(String id, String title, List<String> strokes) =>
    _animal(id, title, "Let's draw $title", strokes.map(_moreStroke).toList());

LessonData _morePicture(
  LessonKind kind,
  String id,
  String title,
  List<String> strokes,
) => _picture(
  kind,
  id,
  title,
  "Let's draw $title",
  strokes.map(_moreStroke).toList(),
);

